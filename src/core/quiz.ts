export const questions = [...baseQuestions, ...formulaQuestions];
export const topics = [...new Set(questions.map(item => item.topic))];

export function makeQuiz(seed: string, topic = 'Все темы', count = 8) {
  const pool = questions.filter(
    item => topic === 'Все темы' || item.topic === topic,
  );
  if (!pool.length) throw new Error('Нет вопросов для этой темы.');
  const rng = random(seed);
  let selection = shuffle(rng, pool).slice(0, count);
  if (topic === FORMULA_TOPIC) {
    const skills: FormulaSkill[] = [
      'meaning',
      'application',
      'evaluation',
      'debugging',
    ];
    const buckets = shuffle(rng, skills).map(skill =>
      shuffle(
        rng,
        pool.filter(item => (item.skill ?? 'application') === skill),
      ),
    );
    selection = [];
    while (selection.length < Math.min(count, pool.length)) {
      for (const bucket of buckets) {
        const question = bucket.pop();
        if (question) selection.push(question);
        if (selection.length >= count) break;
      }
    }
    selection = shuffle(rng, selection);
  }
  return selection.map(item => {
    const order = shuffle(
      rng,
      item.options.map((_, i) => i),
    );
    return {
      ...item,
      options: order.map(i => item.options[i]),
      correct: order.indexOf(item.correct),
    };
  });
}
